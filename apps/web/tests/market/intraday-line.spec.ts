import {test,expect} from '@playwright/test';
test('intraday interval shares one series for chart, table and selection, and survives resizing',async({page})=>{
 await page.setViewportSize({width:390,height:844});
 const points=Array.from({length:12},(_,i)=>({time:`2026100209${String(i+1).padStart(2,'0')}00`,value:100+i}));
 let calls=0;
 await page.route('**/api/market/v1/securities/005930/chart?period=day',route=>{calls++;return route.fulfill({json:{status:'ready',points,session_date:'2026-10-02'}});});
 await page.goto('/stocks?code=005930&mode=intraday&kind=line&period=day');
 const interval=page.getByRole('combobox',{name:'선 차트 간격'});
 await expect(interval).toHaveValue('5min',{timeout:20000});
 const plot=page.locator('.mk-detail .mk-line-chart').first();
 await plot.getByText('차트 데이터 보기 · 5분 구간 마지막 종가',{exact:true}).click();
 await expect(plot.locator('tbody tr')).toHaveCount(3);
 await expect(plot.locator('tbody tr').first()).toContainText('20261002090400');
 const before=calls;
 await interval.selectOption('1min');
 await expect(plot.locator('tbody tr')).toHaveCount(12);
 await plot.getByRole('button',{name:'이전 시점'}).click();
 await expect(plot.locator('.mk-chart-readout')).toContainText('110');
 await interval.selectOption('5min');
 await expect(plot.locator('tbody tr')).toHaveCount(3);
 await expect(plot.locator('.mk-chart-readout')).toContainText('111');
 expect(calls).toBe(before);
 await page.setViewportSize({width:1440,height:900});
 await expect(interval).toHaveValue('5min');
 await page.reload();
 await expect(interval).toHaveValue('5min',{timeout:20000});
 await page.goto('/stocks?code=005930&mode=intraday&kind=line&period=day&lineInterval=1min');
 await expect(interval).toHaveValue('1min',{timeout:20000});
 expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('stocks.chart.005930')||'{}').lineInterval)).toBe('5min');
});
